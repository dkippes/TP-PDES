CREATE TABLE favorito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprador_id BIGINT NOT NULL REFERENCES comprador(id) ON DELETE CASCADE,
    paquete_id BIGINT NOT NULL REFERENCES paquete(id) ON DELETE CASCADE,
    agregado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT favorito_comprador_paquete_unique UNIQUE (comprador_id, paquete_id)
);

CREATE INDEX favorito_paquete_idx ON favorito(paquete_id);
