CREATE TABLE IF NOT EXISTS perfil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS agencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS administrador (
    id BIGINT PRIMARY KEY REFERENCES perfil(id)
);

CREATE TABLE IF NOT EXISTS agente (
    id BIGINT PRIMARY KEY REFERENCES perfil(id),
    agencia_id BIGINT NOT NULL REFERENCES agencia(id)
);

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    apellido VARCHAR(255) NOT NULL,
    correo VARCHAR(255) NOT NULL UNIQUE,
    direccion VARCHAR(255) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    perfil_id BIGINT NOT NULL UNIQUE REFERENCES perfil(id)
);

CREATE TABLE IF NOT EXISTS comprador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id BIGINT NOT NULL UNIQUE REFERENCES perfil(id)
);

CREATE TABLE IF NOT EXISTS hotel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    pais VARCHAR(255) NOT NULL,
    foto VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS paquete (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    precio REAL NOT NULL,
    vuelo_ida_id BIGINT NOT NULL,
    vuelo_vuelta_id BIGINT NOT NULL,
    hotel_id BIGINT NOT NULL REFERENCES hotel(id),
    destino VARCHAR(255) NOT NULL,
    agencia_id BIGINT NOT NULL REFERENCES agencia(id)
);

CREATE TABLE IF NOT EXISTS compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    precio REAL NOT NULL,
    paquete_id BIGINT NOT NULL REFERENCES paquete(id),
    agencia_id BIGINT NOT NULL REFERENCES agencia(id),
    comprador_id BIGINT NOT NULL REFERENCES comprador(id)
);

CREATE TABLE IF NOT EXISTS valoracion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puntaje INTEGER NOT NULL,
    comentario VARCHAR(255) NOT NULL,
    paquete_id BIGINT NOT NULL REFERENCES paquete(id),
    comprador_id BIGINT NOT NULL REFERENCES comprador(id)
);

CREATE TABLE IF NOT EXISTS filtro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS buscador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS buscador_filtro (
    buscador_id BIGINT NOT NULL REFERENCES buscador(id),
    filtro_id BIGINT NOT NULL REFERENCES filtro(id),
    PRIMARY KEY (buscador_id, filtro_id)
);

CREATE TABLE IF NOT EXISTS ping_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    backend_status VARCHAR(255) NOT NULL,
    flying_status VARCHAR(255) NOT NULL,
    flying_response VARCHAR(255)
);
