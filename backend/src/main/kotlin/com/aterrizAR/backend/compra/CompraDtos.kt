package com.aterrizAR.backend.compra

import com.aterrizAR.backend.model.Compra
import com.aterrizAR.backend.model.Paquete
import io.swagger.v3.oas.annotations.media.Schema
import jakarta.validation.constraints.NotNull
import jakarta.validation.constraints.Positive
import java.time.LocalDate
import java.util.UUID

data class CompraRequestDTO(
    @field:NotNull @field:Positive
    val paqueteId: Long?,

    @field:NotNull
    @field:Schema(description = "Generated by the client for each purchase attempt; repeating it returns the original purchase")
    val operacionId: UUID?,
)

/** `paquete` keeps the same shape as the catalog (`GET /api/paquetes`); `precio` is the price paid. */
data class CompraResponseDTO(
    val id: Long,
    val operacionId: UUID,
    val precio: Float,
    val fecha: LocalDate,
    val paquete: Paquete,
)

fun Compra.toDTO() = CompraResponseDTO(
    id = requireNotNull(id), operacionId = operacionId, precio = precio, fecha = fecha, paquete = paquete,
)
