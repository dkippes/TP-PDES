CREATE TABLE venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion_id UUID NOT NULL,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_venta_operacion_id UNIQUE (operacion_id)
);

-- Sold flights are referenced by id only so that deleting a flight keeps working.
CREATE TABLE venta_vuelo (
    venta_id BIGINT NOT NULL REFERENCES venta (id) ON DELETE CASCADE,
    vuelo_id BIGINT NOT NULL,
    PRIMARY KEY (venta_id, vuelo_id)
);
